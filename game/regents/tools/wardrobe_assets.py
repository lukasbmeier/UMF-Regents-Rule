"""The wardrobe's assets: the Knight outfit brought in, and every outfit's DYE ZONES baked.

    python game/regents/tools/wardrobe_assets.py knight   [--src=<Quaternius_Assets>] [--size=1024]
    python game/regents/tools/wardrobe_assets.py zones    [--src=<Quaternius_Assets>] [--preview=<png>]

Both read Luke's extracted Quaternius packs (CC0; default `~/Downloads/04_GameAssets/Quaternius_Assets/`).
Nothing here is generated by an AI model: the outputs are the packs' own pixels, sorted and averaged
(`GAME.md`, "No AI disclosure").

KNIGHT: the foundation's import (`tools/characters/import_quaternius_characters.py`) leaves the Knight out
("armour nobody fishes in"). Regent's Rule wants it (armor), so the GENRE brings it into its own folder,
`game/regents/art/outfits/knight/` (models/ + textures/, textures downscaled to --size), the same way: image
URIs rewritten to ../textures/, no LODs. Its pieces wear on the same 65-bone skeleton as every other outfit.

ZONES: every outfit is ONE painted atlas (`T_<Outfit>_BaseColor`) whose metal is marked by its ORM texture's
blue channel. The packs ship each outfit in three colourways, and WHICH TEXELS CHANGE TOGETHER between them is
how the artist split the outfit into parts to dye. `game/regents/wardrobe/zones.json` (the designer's table)
gives each outfit's parts as reference colours, one per colourway; each texel goes to the nearest reference
(metal ones to "metal"), and the result is `game/regents/wardrobe/zones/T_<Outfit>_Zones.png`:
    R = the slot's index x 40 (0 keep, 1 metal, 2 main, 3 accent, 4 trim, 5 leather, 6 under)
    B = the slot's mean brightness (sRGB-encoded), so the shader keeps each texel's light and dark
The shader (`outfit_dye.gdshader`) reads it with nearest filtering and no mipmaps (the .import written here).
Each colourway is also written as a palette (`wardrobe/palettes/<outfit>_<n>.tres`): the slots' mean colours,
so the lab can put the artist's own colourways back with the shader and compare them with the textures.
Edit zones.json (move a reference, add one), re-run `zones`, open the lab and press Z to see the zones.
"""
import json
import math
import shutil
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
SRC = Path.home() / "Downloads" / "04_GameAssets" / "Quaternius_Assets"
OUTFITS_SRC = "Character Outfits"
KNIGHT = ROOT / "game" / "regents" / "art" / "outfits" / "knight"
WARDROBE = ROOT / "game" / "regents" / "wardrobe"
ZONES_JSON = WARDROBE / "zones.json"
SLOTS = ["keep", "metal", "main", "accent", "trim", "leather", "under"]
SLOT_STEP = 40
SIZE = 1024
NO_LODS = "meshes/generate_lods=false"


def _arg(name: str, default):
    for a in sys.argv[2:]:
        if a.startswith("--%s=" % name):
            return a.split("=", 1)[1]
    return default


# ------------------------------------------------------------------ knight

def _no_lods(model: Path) -> None:
    imp = model.with_name(model.name + ".import")
    if not imp.exists():
        imp.write_bytes(('[remap]\n\nimporter="scene"\ntype="PackedScene"\n\n[params]\n\n%s\n' % NO_LODS).encode())


def knight(src: Path, size: int) -> None:
    parts = src / OUTFITS_SRC / "Exports" / "glTF (Godot-Unreal)" / "Modular Parts"
    (KNIGHT / "models").mkdir(parents=True, exist_ok=True)
    (KNIGHT / "textures").mkdir(parents=True, exist_ok=True)
    wanted = set()
    for gltf in sorted(parts.glob("*_Knight_*.gltf")):
        doc = json.loads(gltf.read_text(encoding="utf-8"))
        for im in doc.get("images", []):
            wanted.add(Path(im["uri"]).name)
            im["uri"] = "../textures/" + Path(im["uri"]).name
        for buf in doc.get("buffers", []):
            shutil.copyfile(gltf.parent / buf["uri"], KNIGHT / "models" / buf["uri"])
        (KNIGHT / "models" / gltf.name).write_bytes(json.dumps(doc, indent=1).encode("utf-8"))
        _no_lods(KNIGHT / "models" / gltf.name)
        print("model", gltf.name)
    # The other two colorways too: the wardrobe lab shows them beside the dye's own (its check).
    wanted |= {"T_Knight_2_BaseColor.png", "T_Knight_3_BaseColor.png"}
    for name in sorted(wanted):
        im = Image.open(src / OUTFITS_SRC / "Textures" / "Knight" / name)
        if max(im.size) > size:
            im = im.resize((size, size), Image.LANCZOS)
        im.save(KNIGHT / "textures" / name, optimize=True)
        print("texture", name)


# ------------------------------------------------------------------ zones

def _srgb_to_linear(c: np.ndarray) -> np.ndarray:
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def _linear_to_srgb(c):
    c = np.clip(c, 0.0, 1.0)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * np.power(c, 1 / 2.4) - 0.055)


def _hex(c) -> np.ndarray:
    c = c.lstrip("#")
    return np.array([int(c[i:i + 2], 16) for i in (0, 2, 4)], np.float32) / 255.0


def _features(cs: list) -> np.ndarray:
    """Per texel: each colourway's chroma (colour without its brightness) and how its brightness changes
    between colourways. Texels of one part share these even where the painting is lighter or darker."""
    lum = [c.mean(-1, keepdims=True) + 0.03 for c in cs]
    f = [c / l / 3.0 for c, l in zip(cs, lum)]
    f += [0.25 * np.log(lum[i] / lum[0]) for i in range(1, len(cs))]
    return np.concatenate(f, -1)


def _load(path: Path, mode: str = "RGB") -> np.ndarray:
    im = Image.open(path).convert(mode)
    if im.size != (SIZE, SIZE):
        im = im.resize((SIZE, SIZE), Image.LANCZOS)
    return np.asarray(im, np.float32) / 255.0


def _mask_import(png: Path) -> None:
    png.with_name(png.name + ".import").write_bytes((
        '[remap]\n\nimporter="texture"\ntype="CompressedTexture2D"\n\n[params]\n\n'
        'compress/mode=0\nmipmaps/generate=false\ndetect_3d/compress_to=0\n').encode())


def _color(c) -> str:
    return "Color(%.4f, %.4f, %.4f, %.4f)" % tuple(c)


def _write_palette(path: Path, title: str, slots: dict, metal: tuple) -> None:
    lines = [
        '[gd_resource type="Resource" script_class="DyePalette" load_steps=4 format=3]',
        "",
        '[ext_resource type="Script" path="res://game/regents/wardrobe/dye_palette.gd" id="1"]',
        '[ext_resource type="Script" path="res://game/regents/wardrobe/metal_finish.gd" id="2"]',
        "",
        '[sub_resource type="Resource" id="metal"]',
        'script = ExtResource("2")',
        'title = "%s metal"' % title,
        "color = %s" % _color(list(metal[0]) + [1.0]),
        "metallic = %.3f" % metal[1],
        "roughness = %.3f" % metal[2],
        "",
        "[resource]",
        'script = ExtResource("1")',
        'title = "%s"' % title,
        'note = "Generated by wardrobe_assets.py zones: the colourway\'s own slot colours (do not edit; copy it)."',
        'metal = SubResource("metal")',
    ]
    for slot in ["main", "accent", "trim", "leather", "under"]:
        lines.append("%s = %s" % (slot, _color(list(slots.get(slot, (0.5, 0.5, 0.5))) + [1.0])))
    path.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))


def zones(src: Path, preview: str) -> None:
    table = json.loads(ZONES_JSON.read_text(encoding="utf-8"))
    (WARDROBE / "zones").mkdir(parents=True, exist_ok=True)
    (WARDROBE / "palettes").mkdir(parents=True, exist_ok=True)
    false_colour = np.array([[0.15, 0.15, 0.15], [0.75, 0.78, 0.85], [0.9, 0.15, 0.15], [0.2, 0.4, 0.95],
                             [1.0, 0.8, 0.1], [0.55, 0.3, 0.1], [0.15, 0.75, 0.3]], np.float32)
    rows = []
    for outfit, spec in table["outfits"].items():
        tex = src / OUTFITS_SRC / "Textures" / outfit
        ways = [_load(tex / ("T_%s%s_BaseColor.png" % (outfit, s))) for s in ["", "_2", "_3"]]
        orm = _load(tex / ("T_%s_ORM.png" % outfit))
        metal = orm[..., 2] > 0.5
        feats = _features(ways)
        refs = []
        ref_slot = []
        for z in spec["zones"]:
            for ref in z["refs"]:
                cs = [_hex(h).reshape(1, 1, 3) for h in ref]
                refs.append(_features(cs).reshape(-1))
                ref_slot.append(SLOTS.index(z["slot"]))
        refs = np.array(refs, np.float32)
        ref_slot = np.array(ref_slot)
        flat = feats.reshape(-1, feats.shape[-1])
        best = np.zeros(flat.shape[0], np.int64)
        best_d = np.full(flat.shape[0], np.inf, np.float32)
        for i, r in enumerate(refs):   # one reference at a time: a 1024^2 x refs table would not fit
            d = ((flat - r) ** 2).sum(-1)
            closer = d < best_d
            best[closer] = i
            best_d[closer] = d[closer]
        slot = ref_slot[best].reshape(SIZE, SIZE)
        slot[metal] = SLOTS.index("metal")
        lin = [_srgb_to_linear(w) for w in ways]
        lum1 = (lin[0] * np.array([0.2126, 0.7152, 0.0722], np.float32)).sum(-1)
        mean_b = np.zeros((SIZE, SIZE), np.float32)
        report = []
        for s in range(1, len(SLOTS)):
            sel = slot == s
            if not sel.any():
                continue
            m = float(lum1[sel].mean())
            mean_b[sel] = float(_linear_to_srgb(m))
            report.append("%s %.0f%%" % (SLOTS[s], 100.0 * sel.mean()))
        mask = np.zeros((SIZE, SIZE, 4), np.uint8)
        mask[..., 0] = slot * SLOT_STEP
        mask[..., 1] = 255
        mask[..., 2] = np.clip(np.round(mean_b * 255.0), 1, 255)
        mask[..., 3] = 255
        out = WARDROBE / "zones" / ("T_%s_Zones.png" % outfit)
        Image.fromarray(mask).save(out, optimize=True)
        _mask_import(out)
        print(outfit, ": ", ", ".join(report))
        # The colourways as palettes: each slot's mean colour (averaged in linear light).
        for n, w in enumerate(lin):
            cols = {}
            for s in range(2, len(SLOTS)):
                sel = slot == s
                if sel.any():
                    cols[SLOTS[s]] = tuple(float(v) for v in _linear_to_srgb(w[sel].mean(0)))
            msel = metal
            mcol = tuple(float(v) for v in _linear_to_srgb(w[msel].mean(0)))
            rough = float(orm[..., 1][msel].mean())
            name = "%s_%d" % (outfit.lower(), n + 1)
            _write_palette(WARDROBE / "palettes" / (name + ".tres"), "%s, colourway %d" % (outfit, n + 1),
                           cols, (mcol, 1.0, rough))
        if preview:
            rows.append(np.concatenate([(ways[0] * 255).astype(np.uint8),
                                        (false_colour[slot] * 255).astype(np.uint8)], 1))
    if preview and rows:
        Image.fromarray(np.concatenate(rows, 0)).resize((800, 400 * len(rows))).save(preview)
        print("preview", preview)


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in ("knight", "zones"):
        print(__doc__)
        sys.exit(1)
    src = Path(_arg("src", str(SRC)))
    if sys.argv[1] == "knight":
        knight(src, int(_arg("size", SIZE)))
    else:
        zones(src, _arg("preview", ""))


if __name__ == "__main__":
    main()
