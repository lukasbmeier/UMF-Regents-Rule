/// Every `shared/world/*.json` becomes `pub static <LEVEL>: LevelBake`, plus `ALL` and `by_name`.
/// The depth grid is `include_bytes!`d from beside the JSON, and its size is checked here so a
/// bake whose grid does not match its header fails the BUILD rather than indexing out of bounds.
fn levels() {
    let dir = PathBuf::from("../shared/world");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut names: Vec<String> = Vec::new();
    let mut ids: Vec<(u8, String)> = Vec::new();
    let mut out = String::from("// @generated by build.rs from shared/world/*.json — do not edit.\n");
    let mut entries: Vec<PathBuf> = match fs::read_dir(&dir) {
        Ok(rd) => rd.filter_map(|e| e.ok().map(|e| e.path())).collect(),
        Err(_) => Vec::new(),
    };
    entries.sort();
    for path in entries {
        if path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", path.display());
        let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let l: Level = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let bin = dir.join(&l.depth_grid.file);
        println!("cargo:rerun-if-changed={}", bin.display());
        let bytes = fs::read(&bin).unwrap_or_else(|e| panic!("{}: {e}", bin.display()));
        let g = &l.depth_grid;
        assert_eq!(
            bytes.len(),
            g.width * g.height,
            "{}: depth grid is {} bytes, header says {}x{}",
            bin.display(),
            bytes.len(),
            g.width,
            g.height
        );
        // Absolute, because the generated file lives in OUT_DIR. Joined rather than
        // canonicalised: on Windows `canonicalize` returns a `\\?\` verbatim path.
        let abs = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap())
            .join("..")
            .join("shared")
            .join("world")
            .join(&l.depth_grid.file);
        let ident = l.level.to_uppercase();
        assert!(l.id != 0, "{}: level id 0 is the level-less world (the greybox); a bake needs its own", path.display());
        if let Some((_, other)) = ids.iter().find(|(i, _)| *i == l.id) {
            panic!("{}: level id {} is already {other}'s", path.display(), l.id);
        }
        ids.push((l.id, l.level.clone()));
        let mut points = String::new();
        for p in &l.points {
            points.push_str(&format!(
                "        Point {{ id: {:?}, kind: {:?}, x: {:?}_f64, y: {:?}_f64, z: {:?}_f64, radius: {:?}_f64, tags: &[{}] }},\n",
                p.id, p.kind, p.x, p.y, p.z, p.radius,
                p.tags.iter().map(|t| format!("{t:?}")).collect::<Vec<_>>().join(", ")
            ));
        }
        let mut spots = String::new();
        for s in &l.spots {
            spots.push_str(&format!(
                "        Spot {{ id: {:?}, name: {:?}, x: {:?}_f64, z: {:?}_f64, radius: {:?}_f64 }},\n",
                s.id, s.name, s.x, s.z, s.radius
            ));
        }
        out.push_str(&format!(
            r#"
pub static {ident}: LevelBake = LevelBake {{
    name: {name:?},
    id: {id},
    water_y: {water:?}_f32,
    spawn: [{sx:?}_f32, {sy:?}_f32, {sz:?}_f32],
    wade_depth: {wade:?}_f32,
    min_cast_dm: {dm},
    origin_x: {ox:?}_f64,
    origin_z: {oz:?}_f64,
    spacing: {sp:?}_f64,
    width: {w},
    height: {h},
    depth_dm: include_bytes!({path:?}),
    spots: &[
{spots}    ],
    points: &[
{points}    ],
}};
"#,
            ident = ident,
            name = l.level,
            id = l.id,
            points = points,
            water = l.water_y,
            sx = l.spawn[0],
            sy = l.spawn[1],
            sz = l.spawn[2],
            wade = l.wade_depth,
            dm = (l.min_cast_depth * 10.0).round() as u8,
            ox = g.origin_x,
            oz = g.origin_z,
            sp = g.spacing,
            w = g.width,
            h = g.height,
            path = abs.display().to_string(),
            spots = spots,
        ));
        names.push(ident);
    }
    out.push_str(&format!(
        "\n/// Every baked level.\npub static ALL: &[&LevelBake] = &[{}];\n",
        names.iter().map(|n| format!("&{n}")).collect::<Vec<_>>().join(", ")
    ));
    out.push_str(
        "\n/// A baked level by its `level` name.\npub fn by_name(name: &str) -> Option<&'static LevelBake> {\n    ALL.iter().copied().find(|l| l.name == name)\n}\n",
    );
    out.push_str(
        "\n/// A baked level by its number (`world_level.level_id`); 0 is no bake (the greybox).\npub fn by_id(id: u8) -> Option<&'static LevelBake> {\n    ALL.iter().copied().find(|l| l.id == id)\n}\n",
    );
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("levels.rs");
    fs::write(dest, out).unwrap();
}
