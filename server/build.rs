//! Bakes shared/ data into Rust so the module and the Godot client read the same numbers:
//!
//!   shared/movement_config.json  -> $OUT_DIR/movement_config.rs (tunables, `movement_config`)
//!   shared/world/<level>.json    -> $OUT_DIR/levels.rs (one `LevelBake` static per level, `level`)
//!   shared/fishing/fight.json    -> $OUT_DIR/fight_data.rs (THE PUMP's tuning and every
//!                                   catch's fight profile, `genre::fight`)
//!   shared/fishing/fishing.json  -> $OUT_DIR/fishing_data.rs (the fishing genre's content,
//!                                   `genre::fishing`)
//!
//!   shared/content/manifest.json -> checks the content bake is current, then
//!   shared/content/*/ability.json   -> $OUT_DIR/content.rs (`content::ABILITIES`) (build/content.rs)
//!
//! Regenerates whenever any of them changes.

use serde::Deserialize;
use std::{env, fs, path::PathBuf};

/// THIS GAME'S GENRES' BUILD STEPS (content they compile in): `build/genres.rs`, owned by the game.
#[path = "build/genres.rs"]
mod genre_build;

/// THE BAKED CONTENT: refuses a stale bake, compiles in what the module seeds (DECISIONS #199).
#[path = "build/content.rs"]
mod content;
#[path = "build/status_rules.rs"]
mod status_rules;
#[path = "build/hold_rules.rs"]
mod hold_rules;

#[derive(Deserialize)]
struct Cfg {
    walk_speed: f32,
    sprint_speed: f32,
    acceleration: f32,
    friction: f32,
    air_control: f32,
    jump_velocity: f32,
    gravity: f32,
    max_slope_deg: f32,
    coyote_time_sec: f32,
    ground_y: f32,
    client_tick_hz: u32,
    server_tick_hz: u32,
    input_batch_size: u32,
    #[serde(default)]
    flap_charges: u32,
    #[serde(default)]
    flap_velocity: f32,
    #[serde(default)]
    dash_impulse: f32,
}

#[derive(Deserialize)]
struct Grid {
    file: String,
    origin_x: f64,
    origin_z: f64,
    spacing: f64,
    width: usize,
    height: usize,
}

#[derive(Deserialize)]
struct SpotDef {
    id: String,
    name: String,
    x: f64,
    z: f64,
    radius: f64,
}

#[derive(Deserialize)]
struct PointDef {
    id: String,
    kind: String,
    x: f64,
    y: f64,
    z: f64,
    #[serde(default)]
    radius: f64,
    #[serde(default)]
    tags: Vec<String>,
}

#[derive(Deserialize)]
struct Level {
    level: String,
    /// The level's number: what `world_level.level_id` says a world runs (DECISIONS #175).
    id: u8,
    water_y: f32,
    spawn: [f32; 3],
    wade_depth: f32,
    min_cast_depth: f32,
    depth_grid: Grid,
    spots: Vec<SpotDef>,
    #[serde(default)]
    points: Vec<PointDef>,
}

fn main() {
    let listed = genres();
    movement_config();
    rules();
    levels();
    genre_build::run(&listed);
    content::run(&listed);
}

/// shared/game.json `compat` -> $OUT_DIR/compat.rs: an empty reducer named `compat_generation_<N>`
/// (DECISIONS #198). It puts the game's compatibility generation in the schema, where a client's
/// contract check sees it before connecting: a build made at generation 1 lists that reducer, so a
/// server at 2 (a deliberate break: what clients simulate changed) refuses it, both ways round.
///
/// UMF_COMPAT_PROBE (tests/export_test.sh only) builds a NEWER server from this source, to play an
/// exported build against: `add` adds a table and a reducer (the old build must still play), `break`
/// is the next generation (it must be refused). Never set for a database anyone plays on.
fn compat_generation(game: &serde_json::Value) {
    println!("cargo:rerun-if-env-changed=UMF_COMPAT_PROBE");
    let probe = env::var("UMF_COMPAT_PROBE").unwrap_or_default();
    let mut n = match game.get("compat") {
        None => 1,
        Some(x) => x.as_u64().filter(|n| *n >= 1).expect("shared/game.json: compat is a whole number, 1 or more"),
    };
    if probe == "break" {
        n += 1;
    }
    let added = if probe == "add" {
        "/// UMF_COMPAT_PROBE=add: what a newer server added.\n\
         #[spacetimedb::table(accessor = compat_probe, public)]\n\
         pub struct CompatProbe { #[primary_key] pub id: u32, pub note: String }\n\
         #[spacetimedb::reducer]\n\
         pub fn compat_probe_action(_ctx: &spacetimedb::ReducerContext, _id: u32) {}\n"
    } else {
        ""
    };
    assert!(probe.is_empty() || probe == "add" || probe == "break", "UMF_COMPAT_PROBE is add or break, not '{probe}'");
    let out = format!(
        "// @generated by build.rs from shared/game.json `compat` — do not edit.\n\
         /// This build's compatibility generation (docs/rules/compatibility.md).\n\
         pub const COMPAT_GENERATION: u32 = {n};\n\
         /// Does nothing: its NAME is the generation, read by clients from the schema.\n\
         #[spacetimedb::reducer]\n\
         pub fn compat_generation_{n}(_ctx: &spacetimedb::ReducerContext) {{}}\n{added}"
    );
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("compat.rs"), out).unwrap();
}

/// shared/game.json -> `cfg(genre_<name>)` for each genre the game is made of (DECISIONS #173), and
/// $OUT_DIR/genres.rs (`ENABLED`, their names in order). A genre is a file `src/game/<name>.rs`; the
/// ones this tree has are found by looking, so adding a genre needs no edit here.
fn genres() -> Vec<String> {
    // UMF_GAME stands in for shared/game.json (tests/genres_test.sh builds the foundation alone).
    println!("cargo:rerun-if-env-changed=UMF_GAME");
    let path = env::var("UMF_GAME").map(PathBuf::from).unwrap_or_else(|_| PathBuf::from("../shared/game.json"));
    println!("cargo:rerun-if-changed={}", path.display());
    println!("cargo:rerun-if-changed=src/game");
    let mut known: Vec<String> = Vec::new();
    if let Ok(rd) = fs::read_dir("src/game") {
        for entry in rd.flatten() {
            let p = entry.path();
            let stem = p.file_stem().and_then(|s| s.to_str()).unwrap_or("").to_string();
            if p.extension().and_then(|e| e.to_str()) == Some("rs") && stem != "mod" {
                known.push(stem);
            }
        }
    }
    known.sort();
    for k in &known {
        println!("cargo:rustc-check-cfg=cfg(genre_{k})");
    }
    let v: serde_json::Value = serde_json::from_str(&fs::read_to_string(&path).expect("shared/game.json missing"))
        .expect("shared/game.json malformed");
    let listed: Vec<String> = v["genres"].as_array().expect("shared/game.json: genres")
        .iter().map(|g| g.as_str().expect("shared/game.json: a genre is a name").to_string()).collect();
    compat_generation(&v);
    let mut seen: Vec<String> = Vec::new();
    for g in &listed {
        assert!(known.contains(g),
            "shared/game.json names the genre '{g}', but there is no server/src/game/{g}.rs (genres here: {known:?})");
        assert!(!seen.contains(g), "shared/game.json lists '{g}' twice");
        seen.push(g.clone());
        println!("cargo:rustc-cfg=genre_{g}");
    }
    let out = format!(
        "// @generated by build.rs from shared/game.json — do not edit.\n/// The genres this build is made of, in shared/game.json's order.\npub const ENABLED: &[&str] = &[{}];\n",
        listed.iter().map(|g| format!("{g:?}")).collect::<Vec<_>>().join(", ")
    );
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("genres.rs"), out).unwrap();
    // The genre layer's modules, declared here so no foundation file names a genre: `game/<name>.rs`
    // (its `pub static <NAME>` is its `Genre`) and, when it has one, `genre/<name>/` or `genre/<name>.rs`.
    let src = env::current_dir().unwrap().join("src");
    let abs = |p: PathBuf| -> String { p.to_string_lossy().replace('\\', "/") };
    let mut layer = String::from("// @generated by build.rs from shared/game.json — do not edit.\n");
    let mut rules = layer.clone();
    for g in &listed {
        layer.push_str(&format!("#[path = {:?}]\npub mod {g};\n", abs(src.join("game").join(format!("{g}.rs")))));
        let dir = src.join("genre").join(g).join("mod.rs");
        let file = src.join("genre").join(format!("{g}.rs"));
        if dir.exists() {
            rules.push_str(&format!("#[path = {:?}]\npub mod {g};\n", abs(dir)));
        } else if file.exists() {
            rules.push_str(&format!("#[path = {:?}]\npub mod {g};\n", abs(file)));
        }
    }
    layer.push_str(&format!("pub static GENRES: &[&dyn Genre] = &[{}];\n",
        listed.iter().map(|g| format!("&{g}::{}", g.to_uppercase())).collect::<Vec<_>>().join(", ")));
    fs::write(out_dir.join("genre_layer.rs"), layer).unwrap();
    fs::write(out_dir.join("genre_rules.rs"), rules).unwrap();
    println!("cargo:rerun-if-changed=src/genre");
    listed
}

#[derive(Deserialize)]
struct Rules {
    /// MOVED to hot rules (DECISIONS #201): present only in a game that has not moved them; refused.
    #[serde(default)]
    player: Option<serde_json::Value>,
    #[serde(default)]
    interact_range_m: Option<serde_json::Value>,
    sessions: Vec<SessionPlan>,
    /// Reducer name (or "default") -> its budget; keys starting with `_` are comments.
    #[serde(default)]
    rate_limits: std::collections::BTreeMap<String, serde_json::Value>,
}

#[derive(Deserialize)]
struct RateRule {
    burst: f32,
    per_sec: f32,
}

#[derive(Deserialize)]
struct SessionPlan {
    kind: u8,
    phases: Vec<PhaseRule>,
    #[serde(default)]
    lobby: Option<LobbyRule>,
    #[serde(default)]
    r#match: Option<MatchRule>,
}

#[derive(Deserialize)]
struct MatchRule {
    #[serde(default)]
    wait_s: f64,
    #[serde(default = "default_end_after_empty_s")]
    end_after_empty_s: f64,
}

/// A world nobody is in ends its match after a minute unless the rules say otherwise.
fn default_end_after_empty_s() -> f64 {
    60.0
}

#[derive(Deserialize)]
struct LobbyRule {
    #[serde(default)]
    ready_up: bool,
    #[serde(default)]
    min_players: u16,
    #[serde(default)]
    teams: Vec<TeamRule>,
}

#[derive(Deserialize)]
struct TeamRule {
    name: String,
}

#[derive(Deserialize)]
struct PhaseRule {
    phase: u8,
    name: String,
    seconds: f64,
}

/// shared/rules.json -> rules.rs: the foundation's rules as the game sets them (DECISIONS #154).
/// A plan is checked here, so a mistake in the file fails the build instead of a round.
fn rules() {
    let src = PathBuf::from("../shared/rules.json");
    println!("cargo:rerun-if-changed={}", src.display());
    let text = fs::read_to_string(&src).expect("shared/rules.json missing");
    let r: Rules = serde_json::from_str(&text).expect("shared/rules.json malformed");
    // A game whose rules.json still sets these would have its values silently ignored: say where they went.
    assert!(r.player.is_none() && r.interact_range_m.is_none(),
        "shared/rules.json: `player.max_health` and `interact_range_m` are hot rules now (DECISIONS #201):          foundation.new_player_health and foundation.interact_range_m in foundation/content/rules/.          If this game used other values than 100 and 3, set them as overrides in its genre's rule set          (the Content dock, type `rules`); then remove both from shared/rules.json.");
    let mut plans = String::new();
    let mut lobbies = String::new();
    let mut matches = String::new();
    let mut kinds: Vec<u8> = Vec::new();
    for s in &r.sessions {
        assert!(!kinds.contains(&s.kind), "rules.json: session kind {} is planned twice", s.kind);
        kinds.push(s.kind);
        assert!(!s.phases.is_empty(), "rules.json: session kind {} has no phases", s.kind);
        let mut seen: Vec<u8> = Vec::new();
        let mut row = String::new();
        for p in &s.phases {
            assert!(!seen.contains(&p.phase), "rules.json: kind {} lists phase {} twice", s.kind, p.phase);
            assert!(p.seconds >= 0.0, "rules.json: phase {} ({}) has negative seconds", p.phase, p.name);
            seen.push(p.phase);
            row.push_str(&format!("({}, {}), ", p.phase, (p.seconds * 1_000_000.0).round() as i64));
        }
        plans.push_str(&format!("    ({}, &[{}]),\n", s.kind, row));
        if let Some(l) = &s.lobby {
            assert!(l.teams.len() < 255, "rules.json: kind {} has too many teams", s.kind);
            let teams: Vec<String> = l.teams.iter().map(|t| format!("{:?}", t.name)).collect();
            lobbies.push_str(&format!(
                "    Lobby {{ kind: {}, ready_up: {}, min_players: {}, teams: &[{}] }},\n",
                s.kind, l.ready_up, l.min_players, teams.join(", ")
            ));
        }
        if let Some(m) = &s.r#match {
            assert!(m.wait_s >= 0.0, "rules.json: kind {} match.wait_s is negative", s.kind);
            assert!(m.end_after_empty_s >= 0.0, "rules.json: kind {} match.end_after_empty_s is negative", s.kind);
            matches.push_str(&format!(
                "    MatchRules {{ kind: {}, wait_micros: {}, end_after_empty_micros: {} }},\n",
                s.kind, (m.wait_s * 1_000_000.0).round() as i64, (m.end_after_empty_s * 1_000_000.0).round() as i64
            ));
        }
    }
    // RATE LIMITS (REVIEW 0.23.1 B3): a burst of at least one call, refilled at a positive rate.
    let mut rates = String::new();
    let mut rate_default = (10.0_f32, 4.0_f32);
    for (name, v) in &r.rate_limits {
        if name.starts_with('_') {
            continue;
        }
        let rule: RateRule = serde_json::from_value(v.clone())
            .unwrap_or_else(|e| panic!("rules.json: rate_limits.{name} needs burst and per_sec ({e})"));
        assert!(rule.burst >= 1.0, "rules.json: rate_limits.{name}.burst must be at least 1");
        assert!(rule.per_sec > 0.0, "rules.json: rate_limits.{name}.per_sec must be above 0");
        if name == "default" {
            rate_default = (rule.burst, rule.per_sec);
        } else {
            rates.push_str(&format!("    RateLimit {{ verb: {name:?}, burst: {:?}_f32, per_sec: {:?}_f32 }},\n", rule.burst, rule.per_sec));
        }
    }
    let out = format!(
        r#"// @generated by build.rs from shared/rules.json — do not edit.
/// Per session kind, its phases in order and how long each lasts (microseconds; 0 holds it).
pub static SESSION_PLANS: &[(u8, &[(u8, i64)])] = &[
{}];
/// Per session kind with a lobby: whether ready-up starts the round, how many players it needs,
/// and its teams by name (DECISIONS #174).
pub static LOBBIES: &[Lobby] = &[
{}];
/// Per session kind that sets them: how long a match's first lobby waits, and how long a world may
/// be empty before its match ends (DECISIONS #182). Kinds not listed take `MatchRules::DEFAULT`.
pub static MATCHES: &[MatchRules] = &[
{}];
/// How often one player may call a reducer that spends from it (REVIEW 0.23.1 B3); any other
/// takes `RATE_DEFAULT`.
pub static RATE_LIMITS: &[RateLimit] = &[
{}];
pub const RATE_DEFAULT: RateLimit = RateLimit {{ verb: "default", burst: {:?}_f32, per_sec: {:?}_f32 }};
"#,
        plans, lobbies, matches, rates, rate_default.0, rate_default.1
    );
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("rules.rs");
    fs::write(dest, out).unwrap();
}

