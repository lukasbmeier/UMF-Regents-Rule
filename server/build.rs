/// Every `shared/world/*.json` becomes `pub static <LEVEL>: LevelBake`, plus `ALL` and `by_name`.
/// The depth grid is `include_bytes!`d from beside the JSON, and its size is checked here so a
/// bake whose grid does not match its header fails the BUILD rather than indexing out of bounds.
fn levels() {
    let dir = PathBuf::from("../shared/world");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut names: Vec<String> = Vec::new();
    let mut ids: Vec<(u8, String)> = Vec::new();
    let mut out = String::from("// @generated by build.rs from shared/world/*.json — do not edit.\n");
    let mut entries: Vec<PathBuf> = match fs::read_dir(&dir) {
        Ok(rd) => rd.filter_map(|e| e.ok().map(|e| e.path())).collect(),
        Err(_) => Vec::new(),
    };
    entries.sort();
    for path in entries {
        if path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", path.display());
        let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let l: Level = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let bin = dir.join(&l.depth_grid.file);
        println!("cargo:rerun-if-changed={}", bin.display());
        let bytes = fs::read(&bin).unwrap_or_else(|e| panic!("{}: {e}", bin.display()));
        let g = &l.depth_grid;
        assert_eq!(
            bytes.len(),
            g.width * g.height,
            "{}: depth grid is {} bytes, header says {}x{}",
            bin.display(),
            bytes.len(),
            g.width,
            g.height
        );
        // Absolute, because the generated file lives in OUT_DIR. Joined rather than
        // canonicalised: on Windows `canonicalize` returns a `\\?\` verbatim path.
        let abs = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap())
            .join("..")
            .join("shared")
            .join("world")
            .join(&l.depth_grid.file);
        let ident = l.level.to_uppercase();
        assert!(l.id != 0, "{}: level id 0 is the level-less world (the greybox); a bake needs its own", path.display());
        if let Some((_, other)) = ids.iter().find(|(i, _)| *i == l.id) {
            panic!("{}: level id {} is already {other}'s", path.display(), l.id);
        }
        ids.push((l.id, l.level.clone()));
        let mut points = String::new();
        for p in &l.points {
            points.push_str(&format!(
                "        Point {{ id: {:?}, kind: {:?}, x: {:?}_f64, y: {:?}_f64, z: {:?}_f64, radius: {:?}_f64, tags: &[{}] }},\n",
                p.id, p.kind, p.x, p.y, p.z, p.radius,
                p.tags.iter().map(|t| format!("{t:?}")).collect::<Vec<_>>().join(", ")
            ));
        }
        let mut spots = String::new();
        for s in &l.spots {
            spots.push_str(&format!(
                "        Spot {{ id: {:?}, name: {:?}, x: {:?}_f64, z: {:?}_f64, radius: {:?}_f64 }},\n",
                s.id, s.name, s.x, s.z, s.radius
            ));
        }
        out.push_str(&format!(
            r#"
pub static {ident}: LevelBake = LevelBake {{
    name: {name:?},
    id: {id},
    water_y: {water:?}_f32,
    spawn: [{sx:?}_f32, {sy:?}_f32, {sz:?}_f32],
    wade_depth: {wade:?}_f32,
    min_cast_dm: {dm},
    origin_x: {ox:?}_f64,
    origin_z: {oz:?}_f64,
    spacing: {sp:?}_f64,
    width: {w},
    height: {h},
    depth_dm: include_bytes!({path:?}),
    spots: &[
{spots}    ],
    points: &[
{points}    ],
}};
"#,
            ident = ident,
            name = l.level,
            id = l.id,
            points = points,
            water = l.water_y,
            sx = l.spawn[0],
            sy = l.spawn[1],
            sz = l.spawn[2],
            wade = l.wade_depth,
            dm = (l.min_cast_depth * 10.0).round() as u8,
            ox = g.origin_x,
            oz = g.origin_z,
            sp = g.spacing,
            w = g.width,
            h = g.height,
            path = abs.display().to_string(),
            spots = spots,
        ));
        names.push(ident);
    }
    out.push_str(&format!(
        "\n/// Every baked level.\npub static ALL: &[&LevelBake] = &[{}];\n",
        names.iter().map(|n| format!("&{n}")).collect::<Vec<_>>().join(", ")
    ));
    out.push_str(
        "\n/// A baked level by its `level` name.\npub fn by_name(name: &str) -> Option<&'static LevelBake> {\n    ALL.iter().copied().find(|l| l.name == name)\n}\n",
    );
    out.push_str(
        "\n/// A baked level by its number (`world_level.level_id`); 0 is no bake (the greybox).\npub fn by_id(id: u8) -> Option<&'static LevelBake> {\n    ALL.iter().copied().find(|l| l.id == id)\n}\n",
    );
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("levels.rs");
    fs::write(dest, out).unwrap();
}

/// `shared/fishing/fishing.json` -> $OUT_DIR/fishing_data.rs, included by `genre::fishing`.
/// Checked here so a content mistake fails the BUILD: a loot table naming a category nobody
/// defined, a catch in a missing category, a level spot with no loot table, a gear track out of
/// order. Every one of those would otherwise be a silent fallback in play.
fn fishing_data() {
    let path = PathBuf::from("../shared/fishing/fishing.json");
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path).expect("shared/fishing/fishing.json missing");
    let v: serde_json::Value = serde_json::from_str(&text).expect("fishing.json malformed");
    let num = |o: &serde_json::Value, k: &str| -> f64 {
        o.get(k).and_then(|x| x.as_f64()).unwrap_or_else(|| panic!("fishing.json: missing number '{k}'"))
    };
    let s = |o: &serde_json::Value, k: &str| -> String {
        o.get(k).and_then(|x| x.as_str()).unwrap_or_else(|| panic!("fishing.json: missing string '{k}'")).to_string()
    };

    let cats = v["categories"].as_array().expect("categories");
    let cat_ids: Vec<String> = cats.iter().map(|c| s(c, "id")).collect();
    let cat_index = |id: &str| -> usize {
        cat_ids.iter().position(|c| c == id).unwrap_or_else(|| panic!("fishing.json: unknown category '{id}'"))
    };
    let mut out = String::from("// @generated by build.rs from shared/fishing/fishing.json — do not edit.\n");

    let t = &v["timing"];
    for (name, key) in [
        ("BITE_MIN_S", "bite_min_s"), ("BITE_MAX_S", "bite_max_s"), ("BITE_CAP_S", "bite_cap_s"),
        ("TELL_LEAD_S", "tell_lead_s"),
        ("HOOKSET_WINDOW_S", "hookset_window_s"), ("HOOKSET_PERFECT_S", "hookset_perfect_s"),
        ("HOOKSET_LATE_S", "hookset_late_s"), ("MIN_REACTION_S", "min_reaction_s"),
        ("CLOCK_SLACK_S", "clock_slack_s"), ("LINE_LIFE_S", "line_life_s"),
    ] {
        out.push_str(&format!("pub const {name}: f32 = {:?}_f32;\n", num(t, key) as f32));
    }
    let c = &v["cast"];
    out.push_str(&format!("pub const MIN_RANGE_M: f32 = {:?}_f32;\n", num(c, "min_range_m") as f32));
    out.push_str(&format!("pub const RANGE_SLACK_M: f32 = {:?}_f32;\n", num(c, "range_slack_m") as f32));
    let e = &v["economy"];
    for (name, key) in [
        ("DEPLETION_PER_CATCH", "depletion_per_catch"), ("REGEN_PER_SECOND", "regen_per_second"),
        ("RICHNESS_FLOOR", "richness_floor"), ("CROWDING_PENALTY", "crowding_penalty"),
    ] {
        out.push_str(&format!("pub const {name}: f32 = {:?}_f32;\n", num(e, key) as f32));
    }

    out.push_str("\npub static CATEGORIES: &[Category] = &[\n");
    for cat in cats {
        out.push_str(&format!(
            "    Category {{ id: {:?}, word: {:?}, rarity: {}, alive: {} }},\n",
            s(cat, "id"), s(cat, "word"), num(cat, "rarity") as u8,
            cat.get("alive").and_then(|x| x.as_bool()).unwrap_or(true)
        ));
    }
    out.push_str("];\n\npub static CATCHES: &[CatchDef] = &[\n");
    let mut seen_catches: Vec<String> = Vec::new();
    for ch in v["catches"].as_array().expect("catches") {
        let id = s(ch, "id");
        assert!(!seen_catches.contains(&id), "fishing.json: catch '{id}' is listed twice");
        seen_catches.push(id.clone());
        let kg = num(ch, "kg");
        assert!(kg > 0.0, "fishing.json: catch '{id}' weighs nothing");
        out.push_str(&format!(
            "    CatchDef {{ id: {:?}, name: {:?}, category: {}, kg: {:?}_f32, value: {}, model: {:?} }},\n",
            id, s(ch, "name"), cat_index(&s(ch, "category")), kg as f32, num(ch, "value") as i64,
            ch.get("model").and_then(|x| x.as_str()).unwrap_or("")
        ));
    }
    out.push_str("];\n");
    for (ci, cid) in cat_ids.iter().enumerate() {
        let _ = ci;
        assert!(
            v["catches"].as_array().unwrap().iter().any(|ch| s(ch, "category") == *cid),
            "fishing.json: category '{cid}' has no catches, so a roll that lands on it catches nothing"
        );
    }

    let loot_of = |o: &serde_json::Value, where_: &str| -> String {
        let loot = o["loot"].as_object().unwrap_or_else(|| panic!("fishing.json: {where_} has no loot"));
        let mut parts: Vec<String> = Vec::new();
        for (cat, w) in loot {
            let w = w.as_f64().unwrap_or_else(|| panic!("fishing.json: {where_}.{cat} is not a number"));
            assert!(w >= 0.0, "fishing.json: {where_}.{cat} is negative");
            parts.push(format!("({}, {:?}_f32)", cat_index(cat), w as f32));
        }
        format!("&[{}]", parts.join(", "))
    };
    let ow = &v["open_water"];
    out.push_str(&format!(
        "\npub static OPEN_WATER: SpotLoot = SpotLoot {{ id: \"\", min_rod: 0, bite_speed: {:?}_f32, loot: {} }};\n",
        num(ow, "bite_speed") as f32, loot_of(ow, "open_water")
    ));
    out.push_str("\npub static SPOTS: &[SpotLoot] = &[\n");
    let spots = v["spots"].as_object().expect("spots");
    let mut spot_ids: Vec<String> = Vec::new();
    for (id, sp) in spots {
        if id.starts_with('_') {
            continue;
        }
        spot_ids.push(id.clone());
        let min_rod = sp["min_rod"].as_u64().unwrap_or_else(|| panic!("fishing.json: spots.{id} has no min_rod"));
        let rods = v["gear"]["rod"].as_array().map(|a| a.len()).unwrap_or(0) as u64;
        assert!(min_rod < rods, "fishing.json: spots.{id}.min_rod {min_rod} is not a rod tier");
        out.push_str(&format!(
            "    SpotLoot {{ id: {:?}, min_rod: {min_rod}, bite_speed: {:?}_f32, loot: {} }},\n",
            id, num(sp, "bite_speed") as f32, loot_of(sp, &format!("spots.{id}"))
        ));
    }
    out.push_str("];\n");

    // Every named spot in every baked level must have a loot table here, or casting into it
    // would quietly fish open water.
    if let Ok(rd) = fs::read_dir("../shared/world") {
        for entry in rd.flatten() {
            let p = entry.path();
            if p.extension().and_then(|x| x.to_str()) != Some("json") {
                continue;
            }
            let lv: serde_json::Value = serde_json::from_str(&fs::read_to_string(&p).unwrap()).unwrap();
            for sp in lv["spots"].as_array().cloned().unwrap_or_default() {
                let sid = s(&sp, "id");
                assert!(
                    spot_ids.contains(&sid),
                    "{}: spot '{sid}' has no loot table in shared/fishing/fishing.json",
                    p.display()
                );
            }
        }
    }

    let gear = &v["gear"];
    for (track, ty, fields) in [
        ("rod", "Rod", ["max_cast_m", "reel_power"]),
        ("reel", "Reel", ["reel_speed", "hookset_window_mult"]),
        ("line", "Line", ["max_load_kg", "tension_ceiling"]),
    ] {
        let tiers = gear[track].as_array().unwrap_or_else(|| panic!("fishing.json: gear.{track}"));
        assert!(!tiers.is_empty(), "fishing.json: gear.{track} is empty");
        out.push_str(&format!("\npub static {}S: &[{ty}] = &[\n", track.to_uppercase()));
        for (i, tier) in tiers.iter().enumerate() {
            assert_eq!(num(tier, "tier") as usize, i, "fishing.json: gear.{track} tiers out of order");
            out.push_str(&format!(
                "    {ty} {{ name: {:?}, cost: {}, {}: {:?}_f32, {}: {:?}_f32 }},\n",
                s(tier, "name"), num(tier, "cost") as i64,
                fields[0], num(tier, fields[0]) as f32, fields[1], num(tier, fields[1]) as f32
            ));
        }
        out.push_str("];\n");
    }

    // THE TIME OF DAY AND THE WEATHER (DECISIONS #168).
    let cond = &v["conditions"];
    let times = cond["times"].as_array().expect("fishing.json: conditions.times");
    let weathers = cond["weather"].as_array().expect("fishing.json: conditions.weather");
    assert!(!times.is_empty() && !weathers.is_empty(), "fishing.json: conditions need a time and a weather");
    let mut cond_ids: Vec<String> = Vec::new();
    out.push_str("\npub static TIMES: &[TimeOfDay] = &[\n");
    for t in times {
        cond_ids.push(s(t, "id"));
        out.push_str(&format!(
            "    TimeOfDay {{ id: {:?}, name: {:?}, bite_speed: {:?}_f32 }},\n",
            s(t, "id"), s(t, "name"), num(t, "bite_speed") as f32
        ));
    }
    out.push_str("];\n\npub static WEATHERS: &[Weather] = &[\n");
    for w in weathers {
        cond_ids.push(s(w, "id"));
        assert!(num(w, "weight") >= 0.0, "fishing.json: weather {} has a negative weight", s(w, "id"));
        out.push_str(&format!(
            "    Weather {{ id: {:?}, name: {:?}, weight: {:?}_f32, bite_speed: {:?}_f32 }},\n",
            s(w, "id"), s(w, "name"), num(w, "weight") as f32, num(w, "bite_speed") as f32
        ));
    }
    out.push_str("];\n\n/// (category index, or usize::MAX for one catch, catch id or \"\", condition id, multiplier)\n");
    out.push_str("pub static LIKES: &[(usize, &str, &str, f32)] = &[\n");
    for (who, likes) in cond["likes"].as_object().expect("fishing.json: conditions.likes") {
        if who.starts_with('_') {
            continue;
        }
        let (cat, catch_id) = if cat_ids.contains(who) {
            (cat_index(who), String::new())
        } else {
            assert!(seen_catches.contains(who), "fishing.json: conditions.likes.{who} is neither a category nor a catch");
            (usize::MAX, who.clone())
        };
        for (c, m) in likes.as_object().unwrap_or_else(|| panic!("fishing.json: conditions.likes.{who}")) {
            assert!(cond_ids.contains(c), "fishing.json: conditions.likes.{who}.{c} is not a time or a weather");
            let m = m.as_f64().unwrap_or_else(|| panic!("fishing.json: conditions.likes.{who}.{c}"));
            assert!(m >= 0.0, "fishing.json: conditions.likes.{who}.{c} is negative");
            out.push_str(&format!("    ({}, {:?}, {:?}, {:?}_f32),\n",
                if cat == usize::MAX { "usize::MAX".to_string() } else { cat.to_string() }, catch_id, c, m as f32));
        }
    }
    out.push_str("];\n");

    // THE RIVAL ANGLER (DECISIONS #169).
    let r = &v["rival"];
    let pair = |k: &str| -> (f32, f32) {
        let a = r[k].as_array().unwrap_or_else(|| panic!("fishing.json: rival.{k}"));
        (a[0].as_f64().unwrap() as f32, a[1].as_f64().unwrap() as f32)
    };
    let stand = r["stand"].as_array().expect("fishing.json: rival.stand");
    let rspots: Vec<String> = r["spots"].as_array().expect("fishing.json: rival.spots")
        .iter().map(|x| x.as_str().unwrap().to_string()).collect();
    for sp in &rspots {
        assert!(spot_ids.contains(sp), "fishing.json: rival.spots names '{sp}', which has no loot table");
    }
    let chances: Vec<String> = r["land_chance"].as_array().expect("fishing.json: rival.land_chance")
        .iter().map(|x| format!("{:?}_f32", x.as_f64().unwrap() as f32)).collect();
    let (rest_lo, rest_hi) = pair("rest_s");
    let (fight_lo, fight_hi) = pair("fight_s");
    out.push_str(&format!(
        "\npub static RIVAL: RivalDef = RivalDef {{ level: {:?}, name: {:?}, stand: [{:?}_f32, {:?}_f32, {:?}_f32], \
         yaw_deg: {:?}_f32, rod_tier: {}, spots: &[{}], rest_s: ({:?}_f32, {:?}_f32), fight_s: ({:?}_f32, {:?}_f32), \
         fight_s_per_kg_sqrt: {:?}_f32, land_chance: &[{}] }};\n",
        s(r, "level"), s(r, "name"),
        stand[0].as_f64().unwrap() as f32, stand[1].as_f64().unwrap() as f32, stand[2].as_f64().unwrap() as f32,
        num(r, "yaw_deg") as f32, num(r, "rod_tier") as u8,
        rspots.iter().map(|x| format!("{x:?}")).collect::<Vec<_>>().join(", "),
        rest_lo, rest_hi, fight_lo, fight_hi, num(r, "fight_s_per_kg_sqrt") as f32, chances.join(", ")
    ));

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("fishing_data.rs");
    fs::write(dest, out).unwrap();
}


/// `shared/fishing/fight.json` -> $OUT_DIR/fight_data.rs, included by `genre::fight`.
///
/// f64 throughout and printed with `{:?}` (the shortest text that reads back to the same bits),
/// because the fight is replayed here and simulated by the client from the same file, and the
/// two must agree to the last bit (`shared/golden/fishing/fight.json`). The gear multipliers the
/// fight uses are taken from `fishing.json` HERE, as f64, not from its f32 gear tables: widening
/// an f32 1.15 is not the 1.15 the client parsed.
fn fight_data() {
    let path = PathBuf::from("../shared/fishing/fight.json");
    let catalog = PathBuf::from("../shared/fishing/fishing.json");
    println!("cargo:rerun-if-changed={}", path.display());
    let v: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&path).expect("shared/fishing/fight.json missing"))
            .expect("fight.json malformed");
    let cat: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&catalog).expect("fishing.json missing")).expect("fishing.json malformed");
    let num = |o: &serde_json::Value, k: &str, where_: &str| -> f64 {
        o.get(k).and_then(|x| x.as_f64()).unwrap_or_else(|| panic!("{where_}: missing number '{k}'"))
    };
    let flag = |o: &serde_json::Value, k: &str, where_: &str| -> bool {
        o.get(k).and_then(|x| x.as_bool()).unwrap_or_else(|| panic!("{where_}: missing bool '{k}'"))
    };
    const PARAMS: &[&str] = &[
        "distance_rate", "give_factor_idle", "give_factor_dead", "cast_to_fight", "fight_min_m", "fight_max_m",
        "spent_power_floor", "spent_wind_penalty",
        "drag_setting", "tension_response", "tension_release", "drag_slip", "slip_metres", "drag_slip_max",
        "shock_gain", "shock_threshold", "snap_grace_seconds", "snap_tension", "overload_fatigue",
        "fatigue_recover", "bare_reel_fraction", "bare_reel_tension", "spent_reel_fraction",
        "rest_reel_fraction", "spent_reel_strain", "run_reel_strain", "pull_response", "load_rate",
        "load_slow_start", "band_approach_s", "overload_limit", "pump_recover", "snag_load_transfer", "snag_break_load",
        "pump_metres", "weak_yield", "perfect_yield", "perfect_fraction", "load_to_tension", "release_dump",
        "overload_tension", "pump_stress", "stress_settle", "pump_stamina_mult", "crank_window", "crank_rate",
        "lateral_speed", "lateral_range", "lateral_run_mult", "wander_min", "wander_max",
        "give_tension_relief", "give_run_damping", "run_take", "shake_per_pump", "shake_decay",
        "hitstop_perfect", "hitstop_snag_free", "perfect_drag_bonus", "late_start_tension",
        "clean_catch_max_peak_tension", "deadlift_load_mult", "deadlift_creep",
    ];
    const PROFILE_F: &[&str] = &[
        "distance_scale", "hold_force", "run_power", "rest_force", "band_centre", "band_width",
        "band_centre_spent", "band_width_spent", "pump_yield", "panic_gain", "burst_drain", "burst_regen",
        "burst_recover", "stamina_drain", "dead_load", "snag_interval_min", "snag_interval_max",
        "snag_duration", "snag_load",
    ];
    let params = &v["params"];
    let known: Vec<&str> = PARAMS.to_vec();
    for k in params.as_object().expect("fight.json: params").keys() {
        assert!(known.contains(&k.as_str()), "fight.json: params.{k} is not something the fight reads");
    }
    let tick_hz = v["tick_hz"].as_u64().expect("fight.json: tick_hz") as u32;
    assert!(tick_hz >= 20 && tick_hz <= 240, "fight.json: tick_hz {tick_hz} is not a frame rate");
    let mut out = String::from("// @generated by build.rs from shared/fishing/fight.json — do not edit.\n");
    out.push_str(&format!("pub const TICK_HZ: u32 = {tick_hz};\n"));
    out.push_str(&format!("pub const MAX_FIGHT_S: f64 = {:?};\n", num(&v, "max_fight_s", "fight.json")));
    out.push_str("pub const BASE: FightParams = FightParams {\n");
    for k in PARAMS {
        out.push_str(&format!("    {k}: {:?},\n", num(params, k, "fight.json params")));
    }
    out.push_str("    perfect_set: false,\n    late_set: false,\n    deadlift: false,\n};\n");

    let profiles = v["profiles"].as_object().expect("fight.json: profiles");
    out.push_str("\npub static PROFILES: &[(&str, Profile)] = &[\n");
    for (id, p) in profiles {
        let w = format!("fight.json profiles.{id}");
        let mut fields = format!("alive: {}, never_tires: {}", flag(p, "alive", &w), flag(p, "never_tires", &w));
        for k in PROFILE_F {
            fields.push_str(&format!(", {k}: {:?}", num(p, k, &w)));
        }
        assert!(num(p, "dead_load", &w) < num(params, "drag_setting", "params"),
            "{w}: its dead load is over the drag, so easing off can never land it");
        out.push_str(&format!("    ({id:?}, Profile {{ {fields} }}),\n"));
    }
    out.push_str("];\n");
    // Every catch the roll can produce must have a fight, or landing it is impossible to replay.
    for ch in cat["catches"].as_array().expect("fishing.json: catches") {
        let id = ch["id"].as_str().expect("catch id");
        assert!(profiles.contains_key(id), "fishing.json catch '{id}' has no profile in fight.json: re-run tools/fishing/gen_fight.py");
    }
    for (name, track, key) in [
        ("ROD_REEL_POWER", "rod", "reel_power"),
        ("REEL_SPEED", "reel", "reel_speed"),
        ("LINE_TENSION_CEILING", "line", "tension_ceiling"),
    ] {
        let tiers = cat["gear"][track].as_array().unwrap_or_else(|| panic!("fishing.json: gear.{track}"));
        let vals: Vec<String> = tiers.iter().map(|t| format!("{:?}", num(t, key, "fishing.json gear"))).collect();
        out.push_str(&format!("pub const {name}: [f64; {}] = [{}];\n", vals.len(), vals.join(", ")));
    }
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("fight_data.rs");
    fs::write(dest, out).unwrap();
}
