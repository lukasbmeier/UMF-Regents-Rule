// THE REGENTS GENRE'S BUILD STEP: its baked content (shared/content/regents/item.json, tree.json, made by
// tools/bake_content.gd from game/regents/content/) -> $OUT_DIR/regents_data.rs, included by
// `genre::regents`. Checked here so a content mistake fails the BUILD: a tree giving an item that does
// not exist, a round that cannot be played, a tool with no tier.

use std::{env, fs, path::PathBuf};

fn baked(name: &str) -> Vec<serde_json::Value> {
    let path = PathBuf::from(format!("../shared/content/regents/{name}.json"));
    println!("cargo:rerun-if-changed={}", path.display());
    let Ok(text) = fs::read_to_string(&path) else { return Vec::new() };
    let v: serde_json::Value = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    v["items"].as_array().cloned().unwrap_or_default()
}

fn int(o: &serde_json::Value, k: &str, what: &str) -> i64 {
    o.get(k).and_then(|x| x.as_i64()).unwrap_or_else(|| panic!("regents content: {what} has no whole number '{k}'"))
}

fn text(o: &serde_json::Value, k: &str, what: &str) -> String {
    o.get(k).and_then(|x| x.as_str()).unwrap_or_else(|| panic!("regents content: {what} has no text '{k}'")).to_string()
}

pub fn regents_data() {
    let items = baked("item");
    let trees = baked("tree");
    let mut out = String::from("// @generated by build.rs from shared/content/regents/*.json — do not edit.\n");
    out.push_str("pub static ITEMS: &[ItemSeed] = &[\n");
    let mut item_ids: Vec<i64> = Vec::new();
    for it in &items {
        let name = text(it, "name", "an item");
        let id = int(it, "id", &name);
        let tag = text(it, "tool_tag", &name);
        let tier = int(it, "tool_tier", &name);
        assert!(tag.is_empty() || tier >= 1, "regents content: the tool '{name}' works no tier");
        item_ids.push(id);
        out.push_str(&format!("    ItemSeed {{ id: {id}, name: {name:?}, max_stack: {}, tool_tag: {tag:?}, tool_tier: {tier} }},\n",
            int(it, "max_stack", &name)));
    }
    out.push_str("];\n\npub static TREES: &[TreeSeed] = &[\n");
    for t in &trees {
        let name = text(t, "name", "a tree");
        let c = &t["chop"];
        let (swing, target, duration) = (int(c, "swing_ms", &name), int(c, "target_chops", &name), int(c, "duration_ms", &name));
        assert!(swing > 0 && duration > 0 && target > 0 && target <= duration / swing + 1,
            "regents content: the tree '{name}' has a round that cannot be played (swing {swing}, target {target}, {duration} ms)");
        let log = int(t, "log_item", &name);
        assert!(item_ids.contains(&log), "regents content: the tree '{name}' gives item {log}, which is not an item");
        let rare = int(t, "rare_item", &name);
        let rare_pm = int(t, "rare_permille", &name);
        assert!(rare_pm == 0 || item_ids.contains(&rare), "regents content: the tree '{name}' has a rare chance and no rare item");
        out.push_str(&format!(
            "    TreeSeed {{ id: {}, name: {name:?}, tier: {}, chop: chop::ChopParams {{ duration_ms: {duration}, swing_ms: {swing}, \
             stagger_ms: {}, branch_permille: {}, safe_segments: {}, target_chops: {target} }}, log_item: {log}, min_axe_tier: {}, \
             afk_ms_per_log: {}, fell_permille: {}, regrow_ms: {}, rare_item: {rare}, rare_permille: {rare_pm} }},\n",
            int(t, "id", &name), int(t, "tier", &name), int(c, "stagger_ms", &name), int(c, "branch_permille", &name),
            int(c, "safe_segments", &name), int(t, "min_axe_tier", &name), int(t, "afk_ms_per_log", &name),
            int(t, "fell_permille", &name), int(t, "regrow_ms", &name)));
    }
    out.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("regents_data.rs"), out).unwrap();
}
