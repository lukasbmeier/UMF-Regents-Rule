"""Golden vectors for fishing's client/server twins: shared/golden/fishing/*.json.

    python tools/fishing/gen_goldens.py

Written independently of both twins, from shared/fishing/fishing.json and NumPy float32:

  hookset.json   genre::fishing::grade_hookset (Rust)  <->  FishingData.grade_hookset (GDScript)

Every number the grade depends on is float32 on the server, so the reference is too: the
reaction as the client would send it, each threshold, and the window as one float32 product.
The reactions sit ON and a hair either side of every boundary, for every reel tier, because a
boundary is exactly where a double-precision client and a single-precision server disagree.
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
f = np.float32


def main() -> None:
    data = json.loads((ROOT / "shared/fishing/fishing.json").read_text(encoding="utf-8"))
    t = data["timing"]
    MIN = f(t["min_reaction_s"])
    WIN = f(t["hookset_window_s"])
    PERF = f(t["hookset_perfect_s"])
    LATE = f(t["hookset_late_s"])
    mults = [r["hookset_window_mult"] for r in data["gear"]["reel"]]

    def grade(reaction: float, mult: float) -> str:
        r = f(reaction)
        if not np.isfinite(r) or r < MIN:
            return "none"
        window = f(WIN * f(mult))
        if r > window:
            return "none"
        if r <= PERF:
            return "perfect"
        if r >= LATE:
            return "late"
        return "good"

    cases = []
    for mult in mults:
        window = float(f(WIN * f(mult)))
        edges = [0.0, float(MIN), float(PERF), float(LATE), window]
        reactions = [-1.0, 0.05, 0.2, 0.45, 0.7, window + 0.2, 3.0]
        for e in edges:
            e32 = f(e)
            reactions += [float(e32), float(np.nextafter(e32, f(-np.inf))), float(np.nextafter(e32, f(np.inf)))]
        for r in sorted(set(reactions)):
            cases.append({"reaction": r, "window_mult": mult, "grade": grade(r, mult)})
    out = ROOT / "shared/golden/fishing/hookset.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    doc = {
        "name": "hookset",
        "_comment": "GENERATED by tools/fishing/gen_goldens.py. genre::fishing::grade_hookset and FishingData.grade_hookset must give every grade exactly.",
        "cases": cases,
    }
    out.write_bytes((json.dumps(doc, indent=1) + "\n").encode("utf-8"))
    counts = {}
    for c in cases:
        counts[c["grade"]] = counts.get(c["grade"], 0) + 1
    print(f"{out.relative_to(ROOT)}: {len(cases)} cases {counts}")


if __name__ == "__main__":
    main()
