"""Probe vectors for the level bake's lookup: shared/golden/level/<level>_probes.json.

    python tools/world/gen_level_probes.py lakeside

Both twins — `server/src/level.rs` (cargo test --test level) and `foundation/sim/level_bake.gd`
(tests/test_runner.gd) — read the bake and must return exactly these answers for every probe.
Written independently of both: the bake's own header and bytes, and plain arithmetic.

Coordinates are rounded to float32 first, because the module receives positions as f32 and the
client's Vector3 is f32: the probe has to be a number both sides can actually be handed. The
lookup itself is f64 (see level.rs), so each coordinate is widened back before any arithmetic.

Re-run after regenerating the level: the expected depths come from the bake.
"""
import json
import math
import random
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def f32(v: float) -> float:
    return struct.unpack("<f", struct.pack("<f", v))[0]


def main(level: str) -> None:
    bake = json.loads((ROOT / "shared/world" / f"{level}.json").read_text(encoding="utf-8"))
    g = bake["depth_grid"]
    data = (ROOT / "shared/world" / g["file"]).read_bytes()
    w, h = g["width"], g["height"]
    ox, oz, sp = float(g["origin_x"]), float(g["origin_z"]), float(g["spacing"])
    min_dm = round(bake["min_cast_depth"] * 10.0)
    spots = bake["spots"]

    def cell(x: float, z: float):
        i = math.floor((x - ox) / sp + 0.5)
        j = math.floor((z - oz) / sp + 0.5)
        if i < 0 or j < 0 or i >= w or j >= h:
            return None
        return [i, j]

    def spot(x: float, z: float):
        for s in spots:
            dx = x - float(s["x"])
            dz = z - float(s["z"])
            if dx * dx + dz * dz <= float(s["radius"]) ** 2:
                return s["id"]
        return None

    pts = []
    named = {
        "spawn": bake["spawn"][0::2],
        "square": [0.0, 96.0],
        "dock_end": [0.0, 16.0],
        "deep_hole": [10.0, -27.0],
        "reed_bay": [-114.0, 16.0],
        "north_drop": [-31.0, -51.0],
        "north_beach": [-10.0, -96.0],
        "rocky_point": [85.0, -42.0],
        "lake_centre": [0.0, -24.0],
        "dock_pier": [0.0, 40.0],
        "dock_head": [3.0, 25.0],
        "off_grid_far": [400.0, 400.0],
    }
    for name, (x, z) in named.items():
        pts.append((name, x, z))
    # Cell edges: exactly on a boundary, and a hair either side of it.
    for k, (i, j) in enumerate([(10, 10), (134, 79), (0, 0), (w - 1, h - 1), (200, 30)]):
        cx = ox + i * sp
        cz = oz + j * sp
        for dx, dz, tag in [(0.5, 0.5, "edge"), (0.4999, 0.4999, "inside"), (0.5001, -0.5001, "across"),
                            (-0.5, -0.5, "lower_edge"), (-0.5001, 0.0, "lower_out")]:
            pts.append((f"cell{k}_{tag}", cx + dx * sp, cz + dz * sp))
    rng = random.Random(0x1A4E)
    for k in range(60):
        pts.append((f"random{k}", rng.uniform(ox - 5, ox + w * sp + 5), rng.uniform(oz - 5, oz + h * sp + 5)))

    probes = []
    for name, x, z in pts:
        x, z = f32(x), f32(z)
        c = cell(x, z)
        dm = data[c[1] * w + c[0]] if c is not None else 0
        probes.append({"name": name, "x": x, "z": z, "cell": c, "depth_dm": dm,
                       "is_water": dm >= min_dm, "spot": spot(x, z)})
    out = ROOT / "shared/golden/level" / f"{level}_probes.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    doc = {"name": f"{level}_probes", "level": level,
           "_comment": "GENERATED by tools/world/gen_level_probes.py from the bake. Both twins must match every probe exactly.",
           "probes": probes}
    out.write_bytes((json.dumps(doc, indent=1) + "\n").encode("utf-8"))
    wet = sum(1 for p in probes if p["is_water"])
    print(f"{out.relative_to(ROOT)}: {len(probes)} probes, {wet} over water")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "lakeside")
